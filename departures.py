# --- Generic Functions ---

def normalize_text(text):
    """Replace Swiss special chars in string by ASCII ones"""
    return "".join(CHAR_MAP.get(c, c) for c in text)


def remove_leading_zeros(s: str):
    """Remove leading zeros in string"""
    i = 0
    while i < len(s) and s[i] == "0":
        i += 1
    return s[i:]


# --- DepartureBoard Class ---

class DepartureBoard:
    """A departure board manages the departures for a specific stop"""

    def __init__(self, stop_id: str):
        self.stop_id = stop_id
        self.departures:list[Departure] = []

    def fetch_departures(self, num: int):
        """Fetch and store new departures. Returns number of departures"""

        gc.collect()

        url = (
            API_BASEURL
            + "?id=" + str(self.stop_id)
            + "&limit=" + str(num)
            + "&type=departure"
            + FIELD_PARAMS
        )

        response = None

        try:
            response = get(url)
            if response.status_code != 200:
                raise OSError(f"[ERROR] API request failed with HTTP {response.status_code}")

            data = response.json()

        finally:
            if response is not None:
                response.close()

        self.departures = [] # clear old cached departures

        for dep in data["stationboard"]:
            category = dep["category"] or ""
            line_number = (category if category not in ["T", "B"] else "") +  remove_leading_zeros(dep["number"])
            line_destination = normalize_text(dep["to"])
            stop = dep["stop"]
            dep_sched_unix = stop["departureTimestamp"]
            dep_est_str = stop["prognosis"]["departure"]

            dep_est_unix = None if not dep_est_str else parse_datetime(dep_est_str)

            departure = Departure(line_number, line_destination, dep_est_unix or dep_sched_unix)

            self.departures.append(departure)

        return len(self.departures)

    def update_departures(self):
        """Remove past departures and sort departures based on eta. Returns number of departures stored."""

        time_now = int(time())
        self.departures = [dep for dep in self.departures if dep.update_eta(time_now) >= 0]
        self.departures.sort(key=lambda dep: (dep.eta_sec, dep.destination))
        return len(self.departures)

    def format_departures(self, lines=4, length=16) -> list[tuple[str, bool]]:
        """Update departures and then nicely format them."""
        self.update_departures()
        current_deps = self.departures[:lines]
        line_width = 1
        eta_width = 1

        for dep in current_deps:
            line_width = max(line_width, len(dep.line_number))
            eta_width = max(eta_width, len(str(dep.eta_min)))

        out_lines = []
        for dep in current_deps:
            formatted = dep.format_line(length, line_width, eta_width)
            out_lines.append((formatted, dep.eta_min == 0))

        return out_lines


# --- Departure Class ---

class Departure:
    "A departure represents a single departure event from a specific stop."

    def __init__(self, line_number: str, destination: str, departure_time: int):
        self.line_number = line_number
        self.dep_time = departure_time
        self.update_eta(time())

        if SHORTEN_DESTINATIONS:
            for keyword, replacement in SHORTEN_KEYWORDS:
                destination = destination.replace(keyword, replacement)

        self.destination = destination


    def update_eta(self, time_now) -> int:
        """Set eta (seconds, minutes) and return eta (seconds) based on given timestamp"""
        eta_seconds = self.dep_time - time_now

        self.eta_sec = eta_seconds
        self.eta_min =  round(eta_seconds/60)

        return self.eta_sec

    def format_line(self, length, line_width=2, eta_width=1):
        """Returns a single line nicely formatted with a fixed width."""
        dest_width = length - line_width - eta_width - 2
        return f"{self.line_number:<{line_width}} {self.destination[:dest_width]:<{dest_width}} {self.eta_min:>{eta_width}}"


