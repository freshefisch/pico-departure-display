# API Documentation: https://transport.opendata.ch/docs.html

from requests import get
from parse_datetime import parse_datetime
from time import time
import gc


# --- Globals ---

API_BASEURL = "https://transport.opendata.ch/v1/stationboard"

SHORTEN_DESTINATIONS = True

SHORTEN_KEYWORDS:list[tuple[str, str]] = [
    ("Zürich, ", ""),
    ("Bahnhof", "Bhf")
]

FIELDS = (
    "stationboard/category",
    "stationboard/number",
    "stationboard/to",
    "stationboard/stop/departureTimestamp",
    "stationboard/stop/delay",
    "stationboard/stop/platform",
    "stationboard/stop/prognosis/departure",
)

FIELD_PARAMS = "".join("&fields[]=" + field for field in FIELDS)

